(() => {
  document.addEventListener("DOMContentLoaded", () => {
    const root = document.getElementById("publication-steps");
    if (!root) return;
    const CFG = window.BS_CONFIG || {};
    const last = CFG.doiInfrastructureActive
      ? "Публикация и регистрация DOI и метаданных"
      : "Публикация и подготовка публикационных метаданных";
    const steps = [
      "Создание учётной записи.",
      "Выбор типа рукописи.",
      "Загрузка рукописи и файлов.",
      "Автоматизированная техническая проверка.",
      "Проверка редакционным офисом.",
      "Первичная научная оценка.",
      "Назначение ответственного редактора.",
      "Приглашение рецензентов.",
      "Независимое рецензирование.",
      "Решение редактора.",
      "Доработка авторами.",
      "Финальное принятие.",
      "Техническое и языковое редактирование.",
      last,
    ];
    root.innerHTML = steps.map((s, i) => `<li><span class="step-num">${i + 1}</span> ${s}</li>`).join("");
  });
})();
